class BitwiseOps {
    public static void main(String[] args) {
        {

            System.out.println(2 << 1);
            System.out.println(2 >> 1);
            System.out.println(2 & 1);
            System.out.println(2 | 1);
            System.out.println(2 ^ 1);
            System.out.println(~1);
        }
    }
    // Expected output : 
    /*  4
     *  1
     *  0
     *  3
     *  3
     *  -2
     */
}